const HORIZON_LABELS = { now: 'сейчас', m3: 'до 3 мес', m12: 'до 12 мес' }
const LEVEL_LABELS = ['', 'низкое', 'среднее', 'высокое']

/** Содержимое по умолчанию для инсайтов без подробной демо-карточки. */
const fallbackDetail = (insight: IPulseInsight): DetailBody => {
  const isHyp = insight.kind === 'hyp'
  const source = insight.updated
  return {
    fact: `${insight.title}.`,
    impact: `${insight.meaning}.`,
    figures: [
      isHyp
        ? { value: insight.strength ?? 'средняя', label: 'сила данных' }
        : {
            value: `${insight.relevance ?? 0}%`,
            label: 'релевантность для компании',
          },
      {
        value: HORIZON_LABELS[insight.horizon ?? 'now'],
        label: 'горизонт влияния',
      },
    ],
    affected: insight.chips.map((chip) => ({
      name: chip,
      description: 'По профилю компании',
      level: insight.level ?? 2,
    })),
    actions: [
      {
        title: 'Обсудить влияние с персональным менеджером',
        description: 'Менеджер разберёт ситуацию компании',
        offer: true,
      },
      {
        title: 'Отслеживать развитие',
        description: 'Пульс сообщит, если оценка изменится',
        cta: 'Подписаться',
      },
    ],
    scenarios: [
      scenario(
        'Вероятно',
        'влияние в пределах текущей оценки',
        'средняя',
        'один источник'
      ),
      scenario(
        'Возможно',
        'эффект окажется слабее',
        'низкая',
        'нет данных о реакции рынка'
      ),
      scenario(
        'Маловероятно',
        'эффект заметно усилится',
        'низкая',
        'сигналов к усилению нет'
      ),
    ],
    sources: [{ name: 'Источник инсайта', description: source }],
    confidence: (insight.level ?? 2) === 3 ? 'высокая' : 'средняя — 1 источник',
    logTime: source,
    log: [],
    questions: [
      {
        question: 'Как это повлияет на нас?',
        answer: `${insight.meaning}. Подробный расчёт появится после сверки с данными компании.`,
      },
    ],
  }
}

/** Шаги «Хода анализа», если для инсайта нет своих. */
const defaultLog = (insight: IPulseInsight, body: DetailBody) => [
  {
    title: 'Собраны материалы по теме',
    description: body.sources.map((source) => source.name).join(', '),
  },
  {
    title: 'Удалены дубли и устаревшие материалы',
    description: 'Учтены публикации за 12 месяцев',
  },
  {
    title: 'Сопоставлено с профилем компании',
    description: insight.chips.join(', '),
  },
  {
    title: 'Оценено влияние',
    description: `Уровень: ${LEVEL_LABELS[insight.level ?? 2]}`,
  },
  {
    title: 'Построены сценарии',
    description: `${body.scenarios.length} сценария`,
  },
  {
    title: 'Сформулированы действия',
    description: `${body.actions.length} действия`,
  },
]

export const getInsightDetail = (insight: IPulseInsight): IInsightDetail => {
  const body = DETAILS[insight.id] ?? fallbackDetail(insight)
  return {
    ...body,
    log: body.log.length ? body.log : defaultLog(insight, body),
    bank: BANK_POSITIONS[insight.id] ?? null,
    risks: [],
    opportunities: [],
    evidence: [],
    warnings: [],
  }
}

export const findInsight = (id: string): IPulseInsight | undefined =>
  PULSE_INSIGHTS[id]
