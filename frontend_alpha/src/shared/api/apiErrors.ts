const BY_CODE: Record<string, string> = {
  COMPANY_NOT_FOUND: 'Компания не найдена',
  INSIGHT_NOT_FOUND: 'Инсайт не найден',
  // Курсор устарел или повреждён — продолжить ленту с этого места нельзя.
  INVALID_CURSOR: 'Не удалось загрузить продолжение ленты — обновите страницу',
  DATABASE_UNAVAILABLE: 'Сервис временно недоступен. Попробуйте позже',
  AI_DISABLED_IN_DEMO: 'Анализ новостей недоступен в демо-режиме',
  AI_ANALYSIS_FAILED: 'Не удалось проанализировать новость',
  ANALYSIS_STORAGE_FAILED: 'Не удалось сохранить результат анализа',
  RUN_STATUS_UNCERTAIN:
    'Не удалось подтвердить результат анализа — проверьте ленту позже',
}

export const humanizeApiError = (code: string | null, fallback: string) =>
  (code && BY_CODE[code]) || fallback
